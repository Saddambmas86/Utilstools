<section class="mb-5" aria-labelledby="tax-estimate-limits">
    <h2 id="tax-estimate-limits" class="h3 mb-3">Scope and limitations</h2>
    <ul>
        <li>Use INR and enter net taxable income, not gross salary. Include the standard deduction and any other eligible deductions in that figure.</li>
        <li>Only resident individuals with ordinary slab-rate income are covered. The calculator does not determine residency or deduction eligibility.</li>
        <li>Special-rate income, such as certain capital gains or winnings, is not calculated.</li>
        <li>Surcharge and marginal relief on surcharge are not calculated. Income above ₹50,00,000 is outside the calculator's supported range.</li>
        <li>Results are estimates, not a tax return or professional tax advice. Confirm your facts and applicable rules before filing.</li>
    </ul>
</section>

