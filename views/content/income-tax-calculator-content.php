<section class="mb-5" aria-labelledby="tax-estimate-scope">
    <h2 id="tax-estimate-scope" class="h3 mb-3">Tax estimate for Tax Year 2026-27</h2>
    <p>This calculator estimates tax for a resident individual on income taxed at normal slab rates. The new regime is selected by default; select the old regime to use its age-based slabs. Enter net taxable income after applying only deductions and exemptions allowed under the selected regime.</p>
    <p class="mb-0">The calculation applies the eligible rebate and 4% Health and Education Cess. It does not calculate deductions for you, tax on special-rate income, surcharge, or other tax adjustments.</p>
</section>

